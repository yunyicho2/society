// AI로 글을 보내기 전에 개인정보로 보이는 글자를 가림.
// 브라우저에서 한 번, 서버에서 한 번 더 적용 (어느 한쪽이 빠져도 원문이 나가지 않게).
//
// 두 단계:
//   strict(기본) — 챗봇 질문·공문 메모. 번호류 + 이름으로 보이는 자리까지 가림
//   doc          — 학교 공식 문서(규정·교육계획서)를 챗봇에 넣을 때. 주민번호·휴대전화·메일만 가림
//                  (교직원 이름·업무분장은 답에 필요한 정보이고, 이름 추정은 문서를 망가뜨림)

// 이름 추정은 흔한 성씨로 시작하는 2~3글자만 대상으로 함 (오탐을 줄이기 위해)
const SUR = '김이박최정강조윤장임한오서신권황안송류유홍전고문양손배백허남심노하곽성차주우구민진지엄채원천방공현함변염여추도석선설마길연위표명반라왕금옥육맹제모탁국';
const NAME = '[' + SUR + '][가-힣]{1,2}';
// 이름 뒤에 붙는 조사
const JOSA = '(?:이|가|은|는|을|를|의|에게|께|와|과|도|랑)?';
// 이름처럼 보이지만 흔한 낱말
const COMMON = /^(현황|강화|안전|조사|조직|진로|진학|지도|지원|정보|정책|정기|성적|성장|신청|신입|전체|전원|전학|주간|주제|한국|문화|문학|미술|수학|과학|영어|국어|체육|음악|기술|가정|보건|상담|안내|심리|선발|신규|기타|이상|이하|이번|이후|이전|이수|임원|연수|연구|연간|공동|공통|공개|공지|교과|고교|고사|고등|교육|교사|방과|방법|방안|배정|백일|남녀|유의|유형|우수|우리|원칙|원격|반장|반별|명단|모든|모두|모집|최소|최대|최종|최근|차시|채점|추천|추가|홍보|황금|하교|하루|함께|허가|노력|서류|서명|손해|송부|육성|국가|마감|길이|도입|도서|석차|선택|선정|설명|위원|표준|평가|금연|제출|제한|권장|권리|변경|면담|여부|염려|양식|오전|오후|장학|장소|장기|정도|학교|학년|학급|학생|학부모|민원|진단|진행|지역|지속|성실|성취|송환|천재|곽란|위기|이해|위한|조기|선수|배경|공정|이주|정서|장애|진단|주의|유지|안정|원활|전문|전담|담당|진학|지난)$/;

const RRN = [/\b\d{6}\s?-\s?[1-4]\d{6}\b/g, '******-*******'];
const MOBILE = [/\b01[016789][-. ]?\d{3,4}[-. ]?\d{4}\b/g, '010-****-****'];
const EMAIL = [/[\w.+-]+@[\w-]+\.[\w.-]+/g, '***@***'];

// 흔한 낱말이거나 형용사·명사 끝(공정한, 이상의, 선택형, 안전부 …)이면 이름이 아님
const notName = name => COMMON.test(name) || /[한는의적형부등성상과와]$/.test(name) && name.length === 3 || /^(하|이상|배경|여건)/.test(name);
const keepName = (m, name, rest, mask) => (notName(name) ? m : mask(name[0] + '○○', rest));

const STRICT = [
  RRN, MOBILE,
  [/\b0\d{1,2}[-. ]\d{3,4}[-. ]\d{4}\b/g, '0**-****-****'],
  EMAIL,
  // 학번 (예: 10507, 2-3-15, 1학년 5반 7번)
  [/\b[123][01]\d[0-4]\d\b(?!\d|[ \t]*원)/g, '*****'],
  [/\b[123][ \t]?-[ \t]?\d{1,2}[ \t]?-[ \t]?\d{1,2}\b/g, '*-*-*'],
  [/([123])[ \t]*학년[ \t]*(\d{1,2})[ \t]*반[ \t]*\d{1,2}[ \t]*번/g, '$1학년 $2반 **번'],
  // '성명: 홍길동', '학생 홍길동' 처럼 이름이 오는 자리 (줄을 넘어가지 않음)
  [new RegExp('(성명|이름|학생명|보호자명|(?:학생|보호자|학부모|담임)(?=[ \\t:：]))([ \\t]*[:：]?[ \\t]*)(' + NAME + ')(' + JOSA + ')(?![가-힣])', 'g'),
    (m, cue, sp, name, josa) => keepName(m, name, josa, (n, r) => cue + sp + n + r)],
  // '홍길동 학생', '홍길동 어머니'
  [new RegExp('(?<![가-힣])(' + NAME + ')([ \\t]*)(학생|학부모|어머니|아버지|보호자)(?![가-힣]*(회|부|실|증|수|들))', 'g'),
    (m, name, sp, t) => keepName(m, name, sp + t, (n, r) => n + r)],
  // 주소의 번지·호수
  [/(\d+)[ \t]*(번길|로|길)[ \t]*\d+(-\d+)?(?![\d.])/g, '$1$2 **'],
  [/\d{1,4}[ \t]*동[ \t]*\d{1,4}[ \t]*호/g, '**동 **호'],
];
const DOC = [RRN, MOBILE, EMAIL];

// names: 가릴 이름 목록(예: 반 명렬). 서버에는 보내지 않고 브라우저에서만 씀
export function maskPII(text, names = [], { level = 'strict' } = {}) {
  let s = String(text || '');
  for (const n of names) {
    if (n && n.length >= 2) s = s.split(n).join(n[0] + '○'.repeat(n.length - 1));
  }
  for (const [re, to] of (level === 'doc' ? DOC : STRICT)) s = s.replace(re, to);
  return s;
}
