// AI로 글을 보내기 전에 개인정보로 보이는 글자를 가림.
// 브라우저에서 한 번, 서버에서 한 번 더 적용 (어느 한쪽이 빠져도 원문이 나가지 않게).

const STOP = /^(전체|모든|해당|각|우리|재학|재학생|신입|졸업|일반|고등|중학|대상|희망|참가|참여|남|여|남녀|타교|본교|일부|다른|학년|학급|담당|지도|위|우수|장애|다문화|특수)$|(학년|반|교|급)$/;
const AFTER = /^(대상|회의|자치|자치회|참여|생활|상담|지도|안전|활동|전원|모두|본인|교사|확인|연락|면담|의견|동의|서명|교육|명단|수|들|및|등|선생님|교무실|협의|개인|정보|보호|출결|결석|지각|조퇴|요청|신청|부담|복지|건강|대표|선발|평가|성적)$/;

const RULES = [
  // 주민등록번호
  [/\b\d{6}\s?-\s?[1-4]\d{6}\b/g, '******-*******'],
  // 휴대전화·일반전화
  [/\b01[016789][-.\s]?\d{3,4}[-.\s]?\d{4}\b/g, '010-****-****'],
  [/\b0\d{1,2}[-.\s]\d{3,4}[-.\s]\d{4}\b/g, '0**-****-****'],
  // 이메일
  [/[\w.+-]+@[\w-]+\.[\w.-]+/g, '***@***'],
  // 학번 (예: 10507, 2-3-15, 1학년 5반 7번)
  [/\b[123][01]\d[0-4]\d\b(?!\d|\s*원)/g, '*****'],
  [/\b[123]\s?-\s?\d{1,2}\s?-\s?\d{1,2}\b/g, '*-*-*'],
  [/([123])\s*학년\s*(\d{1,2})\s*반\s*\d{1,2}\s*번/g, '$1학년 $2반 **번'],
  // '학생 홍길동', '성명: 홍길동', '이름 홍길동' 처럼 이름이 오는 자리
  [/(성명|이름|학생명|보호자명)\s*[:：]?\s*([가-힣])[가-힣]{1,3}(?=[^가-힣]|$)/g, '$1 $2○○'],
  [/(학생|보호자|학부모|담임)\s*[:：]?\s*([가-힣]{2,4})(?=[^가-힣]|$)/g, (m, cue, w) => (AFTER.test(w) ? m : cue + ' ' + w[0] + '○○')],
  // '홍길동 학생' (전체 학생, 해당 학생 같은 말은 그대로)
  [/([가-힣]{2,4})(\s*)(학생|학부모|어머니|아버지)/g, (m, w, sp, t) => (STOP.test(w) ? m : w[0] + '○○' + sp + t)],
  // 주소의 번지·호수
  [/(\d+)\s*(번길|로|길)\s*\d+(-\d+)?/g, '$1$2 **'],
  [/\d{1,4}\s*동\s*\d{1,4}\s*호/g, '**동 **호'],
];

// names: 가릴 이름 목록(예: 반 명렬). 서버에는 보내지 않고 브라우저에서만 씀
export function maskPII(text, names = []) {
  let s = String(text || '');
  for (const n of names) {
    if (n && n.length >= 2) s = s.split(n).join(n[0] + '○'.repeat(n.length - 1));
  }
  for (const [re, to] of RULES) s = s.replace(re, to);
  return s;
}
